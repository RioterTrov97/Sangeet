const fs = require('fs');
const path = require('path');
const { withAndroidManifest, withAppBuildGradle, withDangerousMod, AndroidConfig } = require('@expo/config-plugins');

/**
 * Android support. One universal APK: Platform.isTV (leanback) shows the TV UI, everything else the phone UI.
 *  - leanback launcher category + banner, touchscreen / leanback features not required (so it installs on both)
 *  - no fixed orientation: the phone UI locks portrait per screen (full-screen video turns landscape), the TV is landscape anyway
 *  - INTERNET + media-playback foreground service + notification permissions
 *  - open shared links: ACTION_SEND text and ACTION_VIEW for YouTube / YouTube Music / Spotify links (src/link/)
 *  - Android Auto (media app): automotive_app_desc, unless SANGEET_ANDROID_AUTO=0 (see app.config.ts)
 *  - banner drawable copied from assets/tv/banner.png (generated by scripts/build-icons.mjs)
 *  - release signing from android-keystore/sangeet-release.jks, credentials in the untracked .env.android
 *    (SANGEET_KEYSTORE_PASSWORD, optional SANGEET_KEY_ALIAS) - never committed.
 */
const LINK_HOSTS = ['music.youtube.com', 'www.youtube.com', 'youtube.com', 'm.youtube.com', 'youtu.be', 'open.spotify.com'];

function withTvManifest(config, { androidAuto = true } = {}) {
  return withAndroidManifest(config, (c) => {
    const m = c.modResults.manifest;
    m['uses-feature'] = m['uses-feature'] ?? [];
    for (const [name, required] of [
      ['android.software.leanback', 'false'],
      ['android.hardware.touchscreen', 'false'],
    ]) {
      const f = m['uses-feature'].find((x) => x.$['android:name'] === name);
      if (f) f.$['android:required'] = required;
      else m['uses-feature'].push({ $: { 'android:name': name, 'android:required': required } });
    }
    for (const p of ['android.permission.INTERNET', 'android.permission.FOREGROUND_SERVICE', 'android.permission.FOREGROUND_SERVICE_MEDIA_PLAYBACK', 'android.permission.WAKE_LOCK', 'android.permission.ACCESS_NETWORK_STATE', 'android.permission.ACCESS_WIFI_STATE', 'android.permission.CHANGE_WIFI_MULTICAST_STATE', 'android.permission.POST_NOTIFICATIONS']) {
      AndroidConfig.Permissions.ensurePermission(c.modResults, p);
    }
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(c.modResults);
    app.$['android:banner'] = '@drawable/tv_banner';
    app.$['android:usesCleartextTraffic'] = 'true'; // the in-app stream proxy listens on http://127.0.0.1
    const activity = AndroidConfig.Manifest.getMainActivityOrThrow(c.modResults);
    delete activity.$['android:screenOrientation'];
    // Share a link to Sangeet, or open one from a browser / the YouTube app (MainActivity is singleTask: a running app gets onNewIntent).
    activity['intent-filter'] = activity['intent-filter'] ?? [];
    activity['intent-filter'].push({
      action: [{ $: { 'android:name': 'android.intent.action.SEND' } }],
      category: [{ $: { 'android:name': 'android.intent.category.DEFAULT' } }],
      data: [{ $: { 'android:mimeType': 'text/plain' } }],
    });
    activity['intent-filter'].push({
      action: [{ $: { 'android:name': 'android.intent.action.VIEW' } }],
      category: [{ $: { 'android:name': 'android.intent.category.DEFAULT' } }, { $: { 'android:name': 'android.intent.category.BROWSABLE' } }],
      data: LINK_HOSTS.map((h) => ({ $: { 'android:scheme': 'https', 'android:host': h } })),
    });
    if (androidAuto) {
      app['meta-data'] = (app['meta-data'] ?? []).filter((x) => x.$['android:name'] !== 'com.google.android.gms.car.application');
      app['meta-data'].push({ $: { 'android:name': 'com.google.android.gms.car.application', 'android:resource': '@xml/automotive_app_desc' } });
      // nitro-player 1.9.0 ships the browse service class but does not declare it: Android Auto finds media apps by this filter.
      const BROWSER = 'com.margelo.nitro.nitroplayer.media.NitroPlayerMediaBrowserService';
      app.service = (app.service ?? []).filter((x) => x.$['android:name'] !== BROWSER);
      app.service.push({ $: { 'android:name': BROWSER, 'android:exported': 'true' }, 'intent-filter': [{ action: [{ $: { 'android:name': 'android.media.browse.MediaBrowserService' } }] }] });
    }
    // expo-alternate-app-icons moves the launcher intent onto activity-aliases (one per icon). iOS-only feature: drop the
    // disabled alternates and make the default alias a LEANBACK launcher too.
    const hasCat = (f, name) => (f.category ?? []).some((x) => x.$['android:name'] === name);
    const isLauncher = (f) => hasCat(f, 'android.intent.category.LAUNCHER');
    const addLeanback = (node) => {
      for (const f of node['intent-filter'] ?? []) {
        if (isLauncher(f) && !hasCat(f, 'android.intent.category.LEANBACK_LAUNCHER')) f.category.push({ $: { 'android:name': 'android.intent.category.LEANBACK_LAUNCHER' } });
      }
    };
    app['activity-alias'] = (app['activity-alias'] ?? []).filter((al) => al.$['android:enabled'] !== 'false');
    addLeanback(activity);
    (app['activity-alias'] ?? []).forEach(addLeanback);
    return c;
  });
}

function withAutoDescriptor(config) {
  return withDangerousMod(config, [
    'android',
    (c) => {
      const dir = path.join(c.modRequest.platformProjectRoot, 'app/src/main/res/xml');
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, 'automotive_app_desc.xml'), '<?xml version="1.0" encoding="utf-8"?>\n<automotiveApp>\n  <uses name="media" />\n</automotiveApp>\n');
      return c;
    },
  ]);
}

function withTvBanner(config) {
  return withDangerousMod(config, [
    'android',
    (c) => {
      const src = path.join(c.modRequest.projectRoot, 'assets/tv/banner.png');
      const dir = path.join(c.modRequest.platformProjectRoot, 'app/src/main/res/drawable-xhdpi');
      fs.mkdirSync(dir, { recursive: true });
      fs.copyFileSync(src, path.join(dir, 'tv_banner.png'));
      return c;
    },
  ]);
}

const SIGNING_MARK = '// sangeet-release-signing';
const SIGNING = `
${SIGNING_MARK}
def sangeetEnv = new Properties()
def sangeetEnvFile = new File(rootProject.projectDir.parentFile, '.env.android')
if (sangeetEnvFile.exists()) { sangeetEnvFile.withInputStream { sangeetEnv.load(it) } }
def sangeetKeystore = new File(rootProject.projectDir.parentFile, 'android-keystore/sangeet-release.jks')
def sangeetPassword = System.getenv('SANGEET_KEYSTORE_PASSWORD') ?: sangeetEnv.getProperty('SANGEET_KEYSTORE_PASSWORD')
android {
    signingConfigs {
        sangeetRelease {
            if (sangeetKeystore.exists() && sangeetPassword) {
                storeFile sangeetKeystore
                storePassword sangeetPassword
                keyAlias sangeetEnv.getProperty('SANGEET_KEY_ALIAS') ?: 'sangeet'
                keyPassword sangeetPassword
            }
        }
    }
    buildTypes {
        release {
            if (sangeetKeystore.exists() && sangeetPassword) { signingConfig signingConfigs.sangeetRelease }
        }
    }
}
`;

function withTvSigning(config) {
  return withAppBuildGradle(config, (c) => {
    if (!c.modResults.contents.includes(SIGNING_MARK)) c.modResults.contents += SIGNING;
    return c;
  });
}

module.exports = function withAndroidTV(config, options = {}) {
  config = withTvManifest(config, options);
  if (options.androidAuto !== false) config = withAutoDescriptor(config);
  config = withTvBanner(config);
  config = withTvSigning(config);
  return config;
};
