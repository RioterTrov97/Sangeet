// Bundles src/youtube/extractor/page.ts (runs inside the hidden WebView) into a single HTML string
// exported from src/youtube/extractor/extractorHtml.generated.ts. The output is checked in so a
// fresh clone works even before `npm install` finishes; `postinstall` regenerates it.
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const result = await build({
  entryPoints: [join(root, 'src/youtube/extractor/page.ts')],
  bundle: true,
  write: false,
  format: 'iife',
  platform: 'browser',
  target: 'safari16',
  minify: true,
  legalComments: 'none',
  define: { 'process.env.NODE_ENV': '"production"' },
});
const js = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const html = `<!doctype html><html><head><meta charset="utf-8"></head><body><script>${js}</script></body></html>`;
const out = `// GENERATED by scripts/build-extractor.mjs - do not edit.\nexport const EXTRACTOR_HTML = ${JSON.stringify(html)};\n`;
writeFileSync(join(root, 'src/youtube/extractor/extractorHtml.generated.ts'), out);
console.log(`[build-extractor] wrote ${(html.length / 1024).toFixed(0)} KB`);
